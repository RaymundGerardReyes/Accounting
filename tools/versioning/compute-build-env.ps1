<#
.SYNOPSIS
    Computes build-time version environment variables for Next.js, .NET, and Python.

.DESCRIPTION
    Inspects the repository's `.release-line` marker, active Git branch, tags, and commit SHA
    to compute deterministic build variables:
      - NEXT_PUBLIC_APP_LINE: 'dotnet' | 'python'
      - NEXT_PUBLIC_APP_VERSION: SemVer string stripped of line prefix
      - NEXT_PUBLIC_GIT_SHA: Short commit hash
      - NEXT_PUBLIC_API_CONTRACT: 'v1'
      - NEXT_PUBLIC_BUILD_TIME: ISO 8601 UTC timestamp

.PARAMETER Format
    Output format: 'Text', 'DotEnv', or 'Json'. Default is 'Text'.

.PARAMETER WriteToFrontend
    If specified, writes the variables directly to `Frontend/.env.production.local`.

.EXAMPLE
    ./tools/versioning/compute-build-env.ps1
    ./tools/versioning/compute-build-env.ps1 -Format DotEnv -WriteToFrontend
#>

[CmdletBinding()]
param(
    [ValidateSet('Text', 'DotEnv', 'Json')]
    [string]$Format = 'Text',

    [switch]$WriteToFrontend
)

$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path "$PSScriptRoot/../..").Path

# 1. Determine Line Identity
$lineFile = Join-Path $repoRoot ".release-line"
$line = $null

if (Test-Path $lineFile) {
    $line = (Get-Content $lineFile -Raw).Trim()
}

if ([string]::IsNullOrWhiteSpace($line)) {
    try {
        $branch = (git rev-parse --abbrev-ref HEAD 2>$null).Trim()
        if ($branch -match "c#|dotnet|migrating") {
            $line = "dotnet"
        } else {
            $line = "python"
        }
    } catch {
        $line = "dotnet"
    }
}

# 2. Determine Git SHA
$gitSha = "local-dev"
try {
    $gitSha = (git rev-parse --short HEAD 2>$null).Trim()
    if ([string]::IsNullOrWhiteSpace($gitSha)) { $gitSha = "local-dev" }
} catch {
    $gitSha = "local-dev"
}

# 3. Determine SemVer Tag
$version = $null
$tagPrefix = "$line/v"

try {
    $describeOutput = (git describe --tags --match="$tagPrefix*" 2>$null).Trim()
    if ($describeOutput -and $describeOutput.StartsWith($tagPrefix)) {
        $version = $describeOutput.Substring($tagPrefix.Length)
    }
} catch {
    $version = $null
}

if ([string]::IsNullOrWhiteSpace($version)) {
    if ($line -eq "dotnet") {
        $version = "0.1.0-preview.0"
    } else {
        $legacyVersionFile = Join-Path $repoRoot "VERSION"
        if (Test-Path $legacyVersionFile) {
            $version = (Get-Content $legacyVersionFile -Raw).Trim()
        } else {
            $version = "0.9.34"
        }
    }
}

# 4. Invariants
$apiContract = "v1"
$buildTime = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")

$envVars = [ordered]@{
    "NEXT_PUBLIC_APP_LINE"     = $line
    "NEXT_PUBLIC_APP_VERSION"  = $version
    "NEXT_PUBLIC_GIT_SHA"      = $gitSha
    "NEXT_PUBLIC_API_CONTRACT" = $apiContract
    "NEXT_PUBLIC_BUILD_TIME"   = $buildTime
}

# 5. Output
switch ($Format) {
    'Json' {
        $envVars | ConvertTo-Json -Depth 2
    }
    'DotEnv' {
        $lines = $envVars.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }
        $lines -join "`n"
    }
    Default {
        $envVars.GetEnumerator() | ForEach-Object {
            Write-Output "$($_.Key)=$($_.Value)"
        }
    }
}

if ($WriteToFrontend) {
    $targetPath = Join-Path $repoRoot "Frontend/.env.production.local"
    $lines = $envVars.GetEnumerator() | ForEach-Object { "$($_.Key)=$($_.Value)" }
    $content = "# Auto-generated by tools/versioning/compute-build-env.ps1`n" + ($lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($targetPath, $content, [System.Text.Encoding]::UTF8)
    Write-Host "[INFO] Wrote environment variables to $targetPath" -ForegroundColor Green
}

